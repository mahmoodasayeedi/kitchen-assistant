import { useEffect, useState } from "react";
import { API, errorText, formatTime } from "./api";

export default function RecipeModal({ id, onClose }) {
  const [recipe, setRecipe] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    let cancelled = false;
    async function load() {
      try {
        const res = await fetch(`${API}/recipes/${id}`);
        const data = await res.json().catch(() => null);
        if (cancelled) return;
        if (!res.ok) setError(errorText(data, "Could not load the recipe."));
        else setRecipe(data);
      } catch {
        if (!cancelled) setError("Cannot reach the server. Is the backend running?");
      }
    }
    load();
    return () => {
      cancelled = true;
    };
  }, [id]);

  return (
    <div className="overlay" onClick={onClose}>
      <div className="modal" onClick={(e) => e.stopPropagation()}>
        <button className="close" onClick={onClose} aria-label="Close">×</button>
        {error && <div className="error" style={{ margin: 20 }}>{error}</div>}
        {!recipe && !error && <p style={{ padding: 20 }}>Loading recipe...</p>}
        {recipe && (
          <>
            {recipe.image_url && (
              <img className="hero" src={recipe.image_url} alt={recipe.name} referrerPolicy="no-referrer" />
            )}
            <div className="content">
              <h2>{recipe.name}</h2>
              <div className="tags">
                {recipe.category && <span className="tag">{recipe.category}</span>}
                <span className="tag">⏱ {formatTime(recipe.total_minutes)}</span>
                {recipe.calories != null && <span className="tag">{Math.round(recipe.calories)} kcal</span>}
                {recipe.servings != null && <span className="tag">Serves {recipe.servings}</span>}
              </div>
              {recipe.prep_minutes != null && <p className="small">Prep: {formatTime(recipe.prep_minutes)}</p>}
              {recipe.cook_minutes != null && <p className="small">Cook: {formatTime(recipe.cook_minutes)}</p>}
              <strong>Ingredients</strong>
              <ul>
                {recipe.ingredients.map((ing, i) => <li key={i}>{ing}</li>)}
              </ul>
              <strong>Steps</strong>
              <ol>
                {recipe.steps.map((step, i) => <li key={i}>{step}</li>)}
              </ol>
              <p className="small">Recipe and photo from the Food.com dataset, written by people and not generated by AI.</p>
            </div>
          </>
        )}
      </div>
    </div>
  );
}
